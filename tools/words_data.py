def entry(key):
    if key.startswith("c:"):
        c = COLORS[key[2:]]; return {"k": key, "ko": c[0], "color": c[1], "en": c[2:4], "ja": c[4:6], "zh": c[6:8]}
    if key.startswith("n:"):
        i = int(key[2:]); n = NUMS[i-1]; return {"k": key, "ko": n[0], "num": i, "en": n[1:3], "ja": n[3:5], "zh": n[5:7]}
    w = W[key]; return {"k": key, "ko": w[0], "icon": key, "en": w[1:3], "ja": w[3:5], "zh": w[5:7]}
LV = [("lcards","말 배우기"),("llisten","듣고 고르기"),("lballoon","풍선 터뜨리기"),("lpairs","짝 맞추기 카드"),("lreview","모아 듣기")]
def build():
    books = []
    for i, (t, col, keys) in enumerate(THEMES, 1):
        books.append({"no": i, "title": t, "color": col, "words": [entry(k) for k in keys], "levels": [{"g": g, "p": {}, "name": n} for g, n in LV]})
    return books
